export const GLYPH_H = 7

export interface BlockLayout {
  /** Filled cells as [col, row], in reading order. */
  cells: [number, number][]
  cols: number
  rows: number
}

/** Lays text out on a cell grid: 1 empty column between glyphs, 2 empty rows between lines. */
export function layoutText(text: string, letterGap = 1, lineGap = 2): BlockLayout {
  const cells: [number, number][] = []
  let cols = 0
  const lines = text.toUpperCase().split('\n')
  lines.forEach((line, li) => {
    const top = li * (GLYPH_H + lineGap)
    let x = 0
    for (const ch of line) {
      const g = GLYPHS[ch] ?? GLYPHS['?']
      const w = Math.max(...g.map((r) => r.length))
      for (let r = 0; r < GLYPH_H; r++) {
        for (let c = 0; c < w; c++) if (g[r][c] === '#') cells.push([x + c, top + r])
      }
      x += w + letterGap
    }
    cols = Math.max(cols, x - letterGap)
  })
  return { cells, cols, rows: lines.length * GLYPH_H + (lines.length - 1) * lineGap }
}
